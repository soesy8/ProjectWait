$ErrorActionPreference = 'Stop'
$workspace = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..\..'))
$paths = @(
    'Assets/M/Arts/Fonts/ElevatorKoreanFallback.asset',
    'Assets/M/Arts/Models/ElevatorInteraction/FriendPanicBase.asset',
    'Assets/Test/Art/Materials/Friend/FriendPreviewKorean.asset',
    'Assets/XR/Settings/OpenXRPackageSettings.asset'
)
$gitPath = (Get-Command git).Source
$records = foreach ($relative in $paths) {
    $target = [IO.Path]::GetFullPath((Join-Path $workspace $relative))
    if (-not $target.StartsWith($workspace + [IO.Path]::DirectorySeparatorChar, [StringComparison]::OrdinalIgnoreCase)) { throw 'Target outside workspace.' }
    $startInfo = [Diagnostics.ProcessStartInfo]::new()
    $startInfo.FileName = $gitPath
    $startInfo.WorkingDirectory = $workspace
    $startInfo.ArgumentList.Add('cat-file')
    $startInfo.ArgumentList.Add('--filters')
    $startInfo.ArgumentList.Add('HEAD:' + $relative)
    $startInfo.UseShellExecute = $false
    $startInfo.CreateNoWindow = $true
    $startInfo.RedirectStandardOutput = $true
    $startInfo.RedirectStandardError = $true
    $process = [Diagnostics.Process]::Start($startInfo)
    $memory = [IO.MemoryStream]::new()
    $process.StandardOutput.BaseStream.CopyTo($memory)
    $gitError = $process.StandardError.ReadToEnd()
    $process.WaitForExit()
    if ($process.ExitCode -ne 0) { throw $gitError }
    $original = $memory.ToArray()
    if ($original.Length -lt 100 -or [Text.Encoding]::UTF8.GetString($original,0,5) -ne '%YAML') { throw 'Unexpected original data.' }
    $current = [IO.File]::ReadAllBytes($target)
    $backup = Join-Path $PSScriptRoot ('autogenerated_' + [IO.Path]::GetFileNameWithoutExtension($target) + '.after-review.txt')
    if (-not [IO.File]::Exists($backup)) { [IO.File]::WriteAllBytes($backup,$current) }
    [IO.File]::WriteAllBytes($target,$original)
    $hash = [Convert]::ToHexString([Security.Cryptography.SHA256]::HashData($original))
    [pscustomobject]@{ path=$relative; restoredBytes=$original.Length; restoredSHA256=$hash; backup=[IO.Path]::GetFileName($backup) }
    $process.Dispose()
    $memory.Dispose()
}
$json = $records | ConvertTo-Json -Depth 4
[IO.File]::WriteAllText((Join-Path $PSScriptRoot 'restored_assets.json'),$json,[Text.UTF8Encoding]::new($false))
$records | Select-Object path,restoredBytes | ConvertTo-Json
