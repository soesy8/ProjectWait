var lesson = UnityEngine.Object.FindFirstObjectByType<ProjectWait.M.Elevator.ElevatorLesson>();
var avatar = lesson.friend.GetComponentInChildren<ProjectWait.M.FriendImprovedExpressions>();
var camera = new GameObject("Friend_Validation_Camera").AddComponent<Camera>();
var transforms = lesson.friend.GetComponentsInChildren<Transform>(true);
var previousLayers = transforms.Select(t=>t.gameObject.layer).ToArray();
foreach(var t in transforms)t.gameObject.layer=31;
camera.cullingMask=1<<31;
camera.orthographic = true; camera.orthographicSize = .88f;
camera.nearClipPlane=.02f; camera.farClipPlane=100;
camera.clearFlags=CameraClearFlags.SolidColor; camera.backgroundColor=new Color(.94f,.875f,.75f);
camera.transform.position = lesson.friend.position + lesson.friend.rotation * new Vector3(2,1.3f,-3.4f);
camera.transform.LookAt(lesson.friend.position+Vector3.up*.76f);
ProjectWait.M.Editor.FriendImprovedSetup.Capture(camera,"Assets/M/CodexTemp/FriendImprovement_20261104~/runtime_"+lesson.Flow.Step+".png");
for(int i=0;i<transforms.Length;i++)transforms[i].gameObject.layer=previousLayers[i];
UnityEngine.Object.Destroy(camera.gameObject);
return new { Time.frameCount,step=lesson.Flow.Step.ToString(),expressions=avatar.name };
